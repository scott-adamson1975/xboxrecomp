#!/usr/bin/env python3
"""Writes src/d3d/nv2a_filmup_shaders.h from src/d3d/film_shaders/*.comp
(BO-136, graphics.film_upscale): each pass as GLSL 450 (Vulkan compiles it
at runtime with glslang) and as MSL (Metal compiles it at runtime), the
MSL made with glslangValidator -> SPIR-V -> spirv-cross, as
upscale_wrap.py does. The film shaders are MIT (own code and AMD's FSR 1),
so unlike the LGPL upscaler files they are compiled into the program.

Needs glslangValidator and spirv-cross on the PATH. MIT.

Usage: tools/shaders/film_embed.py      (run after editing a .comp)
"""
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'src' / 'd3d' / 'film_shaders'
OUT = ROOT / 'src' / 'd3d' / 'nv2a_filmup_shaders.h'
PASSES = ['film_deblock', 'film_easu', 'film_rcas', 'film_recombine']


def c_string(text):
    out = []
    for line in text.splitlines():
        line = line.replace('\\', '\\\\').replace('"', '\\"')
        out.append('    "%s\\n"' % line)
    return '\n'.join(out)


def main():
    common = (SRC / 'common.glsl').read_text()
    glsl, msl = [], []
    with tempfile.TemporaryDirectory() as td:
        for name in PASSES:
            text = (SRC / (name + '.comp')).read_text()
            text = text.replace('#include "common.glsl"\n', '')
            # The #version line first, then the pass's own comment.
            text = common + '\n' + text
            comp = pathlib.Path(td) / (name + '.comp')
            spv = pathlib.Path(td) / (name + '.spv')
            out = pathlib.Path(td) / (name + '.metal')
            comp.write_text(text)
            subprocess.run(['glslangValidator', '-V', '--quiet', '-S', 'comp', '-o', str(spv),
                            str(comp)], check=True)
            subprocess.run(['spirv-cross', str(spv), '--msl', '--msl-version', '20100',
                            '--msl-decoration-binding', '--output', str(out)], check=True)
            m = out.read_text()
            if 'pc [[buffer(0)]]' not in m:
                sys.exit(f'{name}: push constants not at buffer(0)')
            glsl.append((name, text))
            msl.append((name, m))
    h = ['/* Generated by tools/shaders/film_embed.py from the .comp files of',
         ' * src/d3d/film_shaders (BO-136). MIT: own code and AMD FidelityFX FSR 1 (MIT, Copyright (c) 2021',
         ' * Advanced Micro Devices, Inc.). Edit the .comp files, not this one. */',
         '#ifndef NV2A_FILMUP_SHADERS_H', '#define NV2A_FILMUP_SHADERS_H', '',
         'enum { FILM_P_DEBLOCK, FILM_P_EASU, FILM_P_RCAS, FILM_P_RECOMBINE, FILM_P_N };', '']
    for kind, items in (('glsl', glsl), ('msl', msl)):
        for name, text in items:
            h.append('static const char k_%s_%s[] =' % (name, kind))
            h.append(c_string(text) + ';')
            h.append('')
        h.append('static const char *const k_film_%s[FILM_P_N] = {' % kind)
        h.append('    ' + ', '.join('k_%s_%s' % (n, kind) for n, _ in items) + ',')
        h.append('};')
        h.append('')
    h.append('#endif')
    OUT.write_text('\n'.join(h) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
